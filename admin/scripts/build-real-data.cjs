const fs = require('node:fs');
const path = require('node:path');
const esbuild = require('esbuild');
const root = path.resolve(__dirname, '..');
const source = fs.readFileSync(path.join(root, 'src/components/RealDataPanels.jsx'), 'utf8')
  .replace("import React from 'react';", 'const React = window.React;')
  .replace("import '../../public/real-data.js';", '')
  .replace(/export function /g, 'function ');
const compiled = esbuild.transformSync(source + '\nwindow.inglyRealUI = { Dashboard, Finance, Monetization };',
  { loader: 'jsx', format: 'iife', target: 'es2020' }).code;
const header = '// GENERATED by scripts/build-real-data.cjs; edit src/components/RealDataPanels.jsx.\n';
const output = path.join(root, 'public/real-data-ui.js');
if (process.argv.includes('--check')) {
  if (fs.readFileSync(output, 'utf8') !== header + compiled) throw new Error('Shared admin UI needs regeneration.');
} else fs.writeFileSync(output, header + compiled);
